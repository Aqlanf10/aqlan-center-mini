/** Server-side compose-only interface. There is no default authenticator,
 * signing key, preview issuer, Server Action, HTTP route, or installer. */
import { randomUUID } from "node:crypto";
import { executePatientNumberingSave, type PatientNumberingControllerDependencies, type PatientNumberingPreviewClaims } from "./patient-numbering-controller";
import type { AppliedNumbering, NumberingOwnerSession, NumberingTransaction } from "./patient-numbering-command";
import { PATIENT_NUMBER_MAX, parseNumberingRequest, planPatientNumbering } from "./patient-numbering-policy";
import { staffAuthorizationFingerprint } from "./staff-capabilities";
import { isNumberingRequestId, type NumberingSettingsTransport, type SettingsNumberingRead } from "./patient-numbering-settings-contract";
import type { NumberingSaveDraft, NumberingSaveTicket, SavePreviewResult } from "../components/settings/patient-numbering-save-model";

type Dependencies = Omit<PatientNumberingControllerDependencies, "currentSessionBinding"> & {
  /** Server-owned preview provider paired with verifyPreview; no implementation
   * here, and no deployment or test-only issuer generated by the composition. */
  issuePreview: (claims: PatientNumberingPreviewClaims, tx: NumberingTransaction) => Promise<string | null>;
};
type Authenticated = NumberingOwnerSession & { actorId: number; fingerprint: string };
function refusal(reason: string): { ok: false; reason: string } { return { ok: false, reason }; }
function revision(value: unknown): value is string {
  return typeof value === "string" && /^[A-Za-z0-9._:-]{1,128}$/.test(value);
}
async function owner(tx: NumberingTransaction): Promise<Authenticated | null> {
  const pair = await tx.ownerSession?.();
  if (!pair || !pair.access.isOwner || typeof pair.sessionBinding !== "string"
    || !pair.sessionBinding || pair.sessionBinding.length > 8192
    || pair.access.userId === null || !Number.isSafeInteger(pair.access.userId) || pair.access.userId <= 0) return null;
  const fingerprint = staffAuthorizationFingerprint(pair.access);
  return fingerprint ? { ...pair, actorId: pair.access.userId, fingerprint } : null;
}
async function stillOwner(tx: NumberingTransaction, first: Authenticated) {
  const fresh = await owner(tx);
  return fresh?.actorId === first.actorId && fresh.fingerprint === first.fingerprint
    && fresh.sessionBinding === first.sessionBinding;
}
function postgresRevision(value: unknown) {
  return revision(value) ? /^(\d{1,19}):([A-Z]{1,6}):([A-Z]{1,6}):([1-9][0-9]{0,17}):([01]):([0-9]{1,18}):([01])$/.exec(value) : null;
}
function validatedReceipt(raw: Awaited<ReturnType<NumberingTransaction["replay"]>>, currentRevision: string): AppliedNumbering | null {
  if (!raw || typeof raw.intent !== "string" || raw.intent.length > 4096 || !raw.result) return null;
  let saved: unknown;
  try { saved = JSON.parse(raw.intent); } catch { return null; }
  if (!Array.isArray(saved) || saved.length !== 4 || JSON.stringify(saved) !== raw.intent
    || !revision(saved[2]) || typeof saved[3] !== "string" || !saved[3] || saved[3].length > 500
    || saved[3].trim() !== saved[3]) return null;
  const parsed = parseNumberingRequest(saved[0], saved[1]);
  if (!parsed || parsed.prefix !== saved[0] || parsed.next !== saved[1]) return null;
  const { prefix, next } = parsed;
  const preview = `${prefix}-${next.padStart(5, "0")}`;
  const result = raw.result;
  const after = result.revision;
  const beforeMark = postgresRevision(saved[2]), afterMark = postgresRevision(after), current = postgresRevision(currentRevision);
  if (result.prefix !== prefix || result.next !== next || result.preview !== preview || !revision(after)
    || !beforeMark || !afterMark || !current || beforeMark[3] !== prefix
    || afterMark[2] !== prefix || afterMark[3] !== prefix || afterMark[4] !== next || afterMark[5] !== "0"
    || beforeMark[7] !== "1" || afterMark[7] !== "1" || beforeMark[6] !== afterMark[6]
    || BigInt(afterMark[1]) !== BigInt(beforeMark[1]) + 1n || BigInt(afterMark[1]) > BigInt(current[1])) return null;
  // Never transmit the stored reason, intent, account/actor identifiers, or preview token.
  return { prefix, next, preview, revision: after };
}
type DispositionResponse = { ok: true; state: "open" | "expired" | "committed" | "retired" } | { ok: false; reason: string };
interface PrivateSettingsTransport extends NumberingSettingsTransport {
  /** Exact owner-only disposition operations, not client mounts or write retries. */
  readDisposition(requestId: string): Promise<DispositionResponse>;
  retireExpired(requestId: string): Promise<DispositionResponse>;
}
class DispositionAuthorityLost extends Error {}
export function createPatientNumberingSettings(dependencies: Dependencies | null = null): PrivateSettingsTransport {
  const installed = dependencies?.backend.authenticatedOwnerSession === true
    && typeof dependencies.issuePreview === "function" && typeof dependencies.verifyPreview === "function" ? dependencies : null;
  const inactive = () => refusal("owner-numbering-not-activated");
  async function resolveDisposition(requestId: string, retire: boolean): Promise<DispositionResponse> {
    if (!installed) return inactive();
    if (!isNumberingRequestId(requestId)) return refusal("invalid-input");
    try {
      return await installed.backend.transaction(async tx => {
        const authority = await owner(tx);
        if (!authority) return refusal("owner-required");
        if (!tx.disposition) return refusal("owner-numbering-not-activated");
        const before = await tx.disposition.inspect(authority.actorId, requestId);
        const receipt = before === "unknown" ? null : await tx.replay(authority.actorId, requestId);
        if (!await stillOwner(tx, authority)) return refusal("owner-required");
        if (before === "unknown" || (before === "committed") !== Boolean(receipt)) return refusal("receipt-unresolved");
        if (before === "committed") {
          const current = await tx.currentNumbering?.();
          if (!current || !validatedReceipt(receipt, current.revision)) return refusal("receipt-unresolved");
        }
        if (!await stillOwner(tx, authority)) return refusal("owner-required");
        if (!retire || before !== "expired") return { ok: true, state: before };
        const after = await tx.disposition.retire(authority.actorId, requestId);
        if (!await stillOwner(tx, authority)) throw new DispositionAuthorityLost();
        if (after === "retired" && await tx.disposition.inspect(authority.actorId, requestId) !== "retired") {
          throw new DispositionAuthorityLost();
        }
        return after === "retired" ? { ok: true, state: after } : refusal("receipt-unresolved");
      });
    } catch (failure) {
      return refusal(failure instanceof DispositionAuthorityLost ? "owner-required" : "numbering-transaction-failed");
    }
  }
  return {
    readDisposition: requestId => resolveDisposition(requestId, false),
    retireExpired: requestId => resolveDisposition(requestId, true),
    async read(requestId): Promise<SettingsNumberingRead> {
      if (!installed) return inactive();
      if (requestId !== null && !isNumberingRequestId(requestId)) return refusal("invalid-input");
      try {
        return await installed.backend.transaction(async tx => {
          const authority = await owner(tx);
          if (!authority) return refusal("owner-required");
          if (installed.requireDisposition && !tx.disposition) return inactive();
          if (installed.requireDisposition && !await tx.disposition?.ready(authority.actorId)) return refusal("owner-required");
          const current = await tx.currentNumbering?.();
          if (!current || !postgresRevision(current.revision)) return refusal("history-unverified");
          // A previous commit is validated against the locked config revision,
          // not against the existence of another allocatable ID.
          const canReplay = requestId && (!tx.disposition
            || await tx.disposition.inspect(authority.actorId, requestId) === "committed");
          const value = canReplay ? validatedReceipt(await tx.replay(authority.actorId, requestId), current.revision) : null;
          if (!await stillOwner(tx, authority)) return refusal("owner-required");
          // Even a locked missing receipt does not prove a prior send will
          // never arrive. Refuse new saves rather than treating that as failed.
          if (requestId && !value) return refusal("receipt-unresolved");
          if (!current.historyComplete) return refusal("history-unverified");
          const next = current.pendingNext ?? current.allocatedThrough + 1n;
          const exhausted = current.pendingNext === null && current.allocatedThrough === PATIENT_NUMBER_MAX;
          if (!/^[A-Z]{1,6}$/.test(current.prefix) || current.historicalThrough < 0n
            || current.historicalThrough > PATIENT_NUMBER_MAX || current.allocatedThrough < 0n
            || (!exhausted && (next < 1n || next <= current.historicalThrough || next > PATIENT_NUMBER_MAX))) {
            return refusal("invalid-snapshot");
          }
          return {
            ok: true, current: { prefix: current.prefix, next: exhausted ? null : next.toString(), revision: current.revision },
            readId: randomUUID(), // non-secret identity for the UI's fresh-read gate
            receipt: requestId && value ? { requestId, value } : null,
          };
        });
      } catch { return refusal("numbering-transaction-failed"); }
    },
    async preview(draft: NumberingSaveDraft): Promise<SavePreviewResult> {
      if (!installed) return inactive();
      const input = parseNumberingRequest(draft?.prefix, draft?.next);
      const reason = typeof draft?.reason === "string" ? draft.reason.trim() : "";
      if (!input || !reason || reason.length > 500) return refusal("invalid-input");
      try {
        return await installed.backend.transaction(async tx => {
          const authority = await owner(tx);
          if (!authority) return refusal("owner-required");
          if (installed.requireDisposition && !tx.disposition) return inactive();
          if (installed.requireDisposition && !await tx.disposition?.ready(authority.actorId)) return refusal("owner-required");
          const snapshot = await tx.snapshot(input.prefix);
          if (!revision(snapshot.revision)) return refusal("invalid-snapshot");
          const plan = planPatientNumbering(input, snapshot, snapshot.revision);
          if (!plan.ok) return plan;
          const expiresAt = tx.disposition ? await tx.disposition.databaseDeadline()
            : (installed.now ?? Date.now)() + 60_000;
          if (!Number.isSafeInteger(expiresAt) || expiresAt <= 60_000) return refusal("numbering-clock-unavailable");
          const command = { ...input, expectedRevision: plan.expectedRevision, reason, requestId: randomUUID() };
          const previewToken = await installed.issuePreview(Object.freeze({
            version: 1, purpose: "patient-numbering.change", actorId: authority.actorId,
            authorityFingerprint: authority.fingerprint, sessionBinding: authority.sessionBinding,
            command: Object.freeze(command), expiresAt,
          }), tx);
          if (!previewToken || typeof previewToken !== "string" || previewToken.length > 8192) return refusal("invalid-preview");
          if (!await stillOwner(tx, authority)) return refusal("owner-required");
          if (tx.disposition) {
            if (!await tx.disposition.register(authority.actorId, command.requestId, expiresAt)) return refusal("receipt-unresolved");
            if (!await stillOwner(tx, authority)
              || await tx.disposition.inspect(authority.actorId, command.requestId, expiresAt) !== "open") {
              throw new DispositionAuthorityLost();
            }
          }
          return { ok: true, ticket: { ...command, preview: plan.preview, previewToken } };
        });
      } catch { return refusal("numbering-transaction-failed"); }
    },
    async save(ticket: NumberingSaveTicket) {
      if (!installed) return inactive();
      const parsed = parseNumberingRequest(ticket?.prefix, ticket?.next);
      if (!parsed || ticket.preview !== `${parsed.prefix}-${parsed.next.padStart(5, "0")}`) return refusal("invalid-input");
      const { prefix, next, expectedRevision, requestId, reason, previewToken } = ticket;
      // Existing controller revalidates the authenticated owner and exact
      // intent around lookup/replay/apply on the same PostgreSQL transaction.
      return executePatientNumberingSave({ prefix, next, expectedRevision, requestId, reason, previewToken }, installed);
    },
  };
}
