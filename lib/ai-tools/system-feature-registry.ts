/**
 * البحث في سجل ميزات وشاشات النظام بناء على استفسار المستخدم
 */
export function findSystemFeature(query: string, userRole?: Role): SystemFeature | null {
  const q = query.toLowerCase().trim();

  let bestMatch: SystemFeature | null = null;
  let maxScore = 0;

  for (const feature of SYSTEM_FEATURES) {
    // التحقق من الصلاحية إن توفر الدور
    if (userRole && !feature.allowedRoles.includes(userRole)) {
      continue;
    }

    let score = 0;
    if (q.includes(feature.name.toLowerCase())) score += 10;
    if (q.includes(feature.id)) score += 8;

    for (const kw of feature.keywords) {
      if (q.includes(kw.toLowerCase())) {
        score += 3;
      }
    }

    if (score > maxScore && score >= 3) {
      maxScore = score;
      bestMatch = feature;
    }
  }

  return bestMatch;
}

