#!/usr/bin/env node
import { createHash } from "node:crypto";
import { lstat, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateRuntimeSourceMap } from "./verify-braces-runtime.mjs";
import { inspectMap } from "./dependency-security/verify-lint-tooling-runtime.mjs";

const fail = message => { throw new Error(`STANDALONE_ENTRY_REJECTED: ${message}`); };
const digest = bytes => createHash("sha256").update(bytes).digest("hex");

// Check every component instead of following links out of either build tree.
async function checkedFile(base, relative, optional = false) {
  const parts = relative.split("/");
  if (parts.some(part => !part || part === "." || part === "..") || path.isAbsolute(relative)) fail("unsafe relative path");
  let current = base;
  for (let i = 0; i < parts.length; i++) {
    current = path.join(current, parts[i]);
    let stat;
    try { stat = await lstat(current); } catch (error) {
      if (optional && error.code === "ENOENT") return null;
      throw error;
    }
    if (stat.isSymbolicLink() || (i + 1 === parts.length ? !stat.isFile() : !stat.isDirectory())) fail(`non-regular path: ${relative}`);
  }
  return readFile(current);
}

async function entries(base, relative) {
  const result = [];
  const queue = [relative];
  while (queue.length) {
    const current = queue.pop();
    // Missing pages is legitimate for an app-only build, but links are not.
    let directory = base, missing = false;
    for (const part of current.split("/")) {
      directory = path.join(directory, part);
      let stat;
      try { stat = await lstat(directory); } catch (error) {
        if (error.code === "ENOENT" && current === relative) { missing = true; break; }
        throw error;
      }
      if (!stat.isDirectory() || stat.isSymbolicLink()) fail(`invalid entry directory: ${current}`);
    }
    if (missing) continue;
    for (const item of await readdir(path.join(base, current), { withFileTypes: true })) {
      const child = `${current}/${item.name}`;
      if (item.isSymbolicLink()) fail(`entry symlink: ${child}`);
      if (item.isDirectory()) queue.push(child);
      else if (item.isFile() && child.endsWith(".js")) result.push(child);
      else if (!item.isFile()) fail(`non-regular entry: ${child}`);
    }
  }
  return result;
}

/** Collect only the literal R.c bootstrap dependencies generated by Next.
 * Unknown syntax fails rather than silently omitting a dependency. */
export function entryChunks(source) {
  const calls = [...source.matchAll(/(?<![\w$])R\s*\.\s*c\s*\(/g)];
  const objectCalls = [...source.matchAll(/(?<![\w$])[A-Za-z_$][\w$]*\s*\.\s*c\s*\(/g)];
  const lines = [...source.matchAll(/^R\.c\("([^"\r\n]+)"\)\s*;?\s*$/gm)];
  if (objectCalls.length !== calls.length || calls.length !== lines.length) fail("unrecognized entry chunk syntax");
  return lines.map(([, name]) => {
    if (!/^server\/chunks\/(?:[A-Za-z0-9_@.\[\]~-]+\/)*[A-Za-z0-9_@.\[\]~-]+\.js$/.test(name)
      || name.split("/").some(part => part === "." || part === "..")) fail("unsafe entry chunk path");
    return name;
  });
}

/** Bind entry points to their build versions, then add missing referenced JS.
 * Do not add source maps: they can include the original application source.
 * Inspect available build maps with the existing security checks regardless,
 * so omitting a map cannot conceal an otherwise rejected dependency input.
 * Existing files are never overwritten or removed. */
export async function assembleStandaloneEntryChunks(projectRoot) {
  const root = path.resolve(projectRoot);
  const build = path.join(root, ".next");
  const standalone = path.join(build, "standalone", ".next");
  for (const directory of [root, build, path.join(build, "standalone"), standalone]) {
    const stat = await lstat(directory);
    if (!stat.isDirectory() || stat.isSymbolicLink()) fail("invalid build root");
  }
  const scripts = [...await entries(standalone, "server/app"), ...await entries(standalone, "server/pages")];
  if (!scripts.length) fail("missing standalone entries");
  const refs = new Set();
  for (const entry of scripts) {
    if (entry.endsWith("_client-reference-manifest.js")) continue;
    const shipped = await checkedFile(standalone, entry);
    const names = entryChunks(shipped.toString("utf8"));
    const bootstrap = /^var R=require\("([^"\r\n]+)"\)\("([^"\r\n]+)"\)\s*;?\s*$/m.exec(shipped.toString("utf8"));
    if (!names.length || !bootstrap || bootstrap[2] !== entry) fail(`unrecognized entry bootstrap: ${entry}`);
    const runtime = path.posix.normalize(path.posix.join(path.posix.dirname(entry), bootstrap[1]));
    if (!runtime.startsWith("server/chunks/") || !runtime.endsWith(".js") || path.posix.isAbsolute(bootstrap[1])) fail(`unsafe entry runtime: ${entry}`);
    const original = await checkedFile(build, entry);
    if (digest(shipped) !== digest(original)) fail(`entry differs from build: ${entry}`);
    refs.add(runtime);
    for (const name of names) refs.add(name);
  }
  if (!refs.size) fail("no literal entry chunk references");
  const plan = [];
  for (const name of [...refs].sort()) {
    const original = await checkedFile(build, name);
    const shipped = await checkedFile(standalone, name, true);
    if (shipped && digest(shipped) !== digest(original)) fail(`shipped chunk differs from build: ${name}`);
    // A data URL embeds the map (and potentially sourcesContent) in the JS.
    if (!shipped && /[#@]\s*sourceMappingURL\s*=\s*data:/i.test(original.toString("utf8"))) fail("inline source map in entry chunk");
    const map = await checkedFile(build, `${name}.map`, true);
    const shippedMap = await checkedFile(standalone, `${name}.map`, true);
    if (shippedMap && (!map || digest(shippedMap) !== digest(map))) fail(`shipped map differs from build: ${name}`);
    if (map) {
      try {
        const parsed = JSON.parse(map.toString("utf8"));
        validateRuntimeSourceMap(parsed, "build source map");
        inspectMap(parsed);
      } catch {
        fail("build source map failed dependency validation");
      }
    }
    if (!shipped) {
      plan.push({ name, original });
    }
  }
  for (const { name, original } of plan) {
    const parts = name.split("/"); parts.pop(); let directory = standalone;
    for (const part of parts) {
      directory = path.join(directory, part);
      try { await mkdir(directory); } catch (error) { if (error.code !== "EEXIST") throw error; }
      const stat = await lstat(directory);
      if (!stat.isDirectory() || stat.isSymbolicLink()) fail(`invalid destination directory: ${name}`);
    }
    await writeFile(path.join(standalone, name), original, { flag: "wx" });
    const copied = await checkedFile(standalone, name);
    if (digest(copied) !== digest(original)) fail(`copied bytes differ: ${name}`);
  }
  return { entries: scripts.length, chunks: refs.size, copied: plan.map(item => item.name) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 2) fail("no arguments accepted");
    const result = await assembleStandaloneEntryChunks(process.cwd());
    console.log(`Standalone entry assembly: ${result.entries} entries, ${result.chunks} chunks, ${result.copied.length} files added.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
