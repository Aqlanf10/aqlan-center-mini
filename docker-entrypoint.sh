#!/bin/sh
set -e

# ── تهيئة القرص الدائم ثم إسقاط صلاحية الجذر ────────────────────────────────
#
# القرص الملحق يُركَّب بملكية الجذر، والتطبيق يعمل بمستخدمٍ غير جذر — فلا يستطيع
# الكتابة عليه. والحلّ ليس تشغيل التطبيق بالجذر: ثغرةٌ فيه تصل إلى ما يصل إليه
# مُشغِّله، ولا يُشغَّل بصلاحية الجذر ما يستقبل طلبات من الإنترنت.
#
# فتبدأ الحاوية بالجذر لحظةً واحدة: تُنشئ المجلّد وتُملّكه للمستخدم، ثم `su-exec`
# يستبدل العملية بأخرى تعمل باسمه. فلا تبقى صلاحية الجذر في العملية التي تخدم
# الطلبات — وهي اللحظة الوحيدة التي تُحتاج فيها.
if [ -n "$DOCUMENTS_DIR" ]; then
  mkdir -p "$DOCUMENTS_DIR"
  # غير متعدٍّ (بلا -R): المجلّد الأعلى يكفي — وما تحته يُنشئه التطبيق بنفسه
  # فيملكه. و`chown -R` على قرصٍ فيه آلاف الأشعة يُبطئ كل إقلاع بلا فائدة.
  chown nextjs:nodejs "$DOCUMENTS_DIR"
fi

# نظام النسخ الاحتياطي يكتب أرشيفاته وحالته تحت جذر الـVolume نفسه. Railway
# يركّب الـVolume بملكية root، لذلك لا يستطيع Next.js (UID 1001) إنشاء أول
# /backups مباشرةً تحت الجذر. نهيّئ المجلدين هنا بعد تركيب الـVolume وقبل إسقاط
# الصلاحيات؛ بعدها كل ملفات النسخ والحالة تُنشأ بواسطة التطبيق غير الجذر.
if [ -n "$RAILWAY_VOLUME_MOUNT_PATH" ]; then
  BACKUP_DIR="$RAILWAY_VOLUME_MOUNT_PATH/backups"
  BACKUP_STATE_DIR="$BACKUP_DIR/.backup-state"
  mkdir -p "$BACKUP_STATE_DIR"
  chown nextjs:nodejs "$BACKUP_DIR" "$BACKUP_STATE_DIR"
  chmod 700 "$BACKUP_DIR" "$BACKUP_STATE_DIR"
fi

exec su-exec nextjs "$@"
