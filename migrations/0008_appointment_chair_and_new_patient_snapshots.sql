-- كلتاهما كُشفتا بمراجعةٍ على البي آر، وكلتاهما من النوع نفسه: المحرّك كان يسأل
-- عن حقيقةٍ لا يملكها، فيفترضها.
--
-- ١) `occupies_chair`: كان عدُّ الكراسي المشغولة يعدّ **كلَّ** موعدٍ متداخل، ولو
--    كانت خدمته لا تشغل كرسيًّا أصلًا (استشارةٌ بالهاتف مثلًا). فمركزٌ بكرسيٍّ
--    واحد تُرفض فيه حشوةٌ لأنّ استشارةً هاتفية «تشغل» الكرسي. والافتراضيّ TRUE
--    لأنّ كلّ ما حُجز قبل هذا العمود كان يشغل كرسيًّا فعلًا.
--
-- ٢) `is_new_patient`: حدُّ المرضى الجدد اليوميّ كان يُقرأ من الإعدادات ويُمرَّر
--    إلى المحرّك، والمحرّك يقارنه بعددٍ **لا أحد يحسبه** — فلا يمنع شيئًا مهما
--    ضُبط. واللقطة تجعل العدّ ممكنًا من مواعيد اليوم نفسها.
--
-- ولقطةٌ لا قراءةٌ حيّة من الخدمة: تعديلُ الخدمة غدًا لا يُعيد رسم ما حُجز اليوم
-- — وهو المبدأ نفسه الذي تتبعه المدّة والفواصل.

