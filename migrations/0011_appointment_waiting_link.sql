-- (المرحلة ٥ — مراجعة المالك) الرابطُ الدائم بين الموعد وصفّ الانتظار الذي وَلَده.
--
-- العطب الذي يُغلقه: التحويل كان ثلاث خطوات — مطالبةٌ مؤقّتة، ثمّ كتابةُ الموعد
-- (تُثبَّت في معاملتها)، ثمّ إغلاقُ الصفّ. وبين الثانية والثالثة نافذةٌ: لو سقطت
-- العملية هناك بقي موعدٌ موجود وصفٌّ مفتوح، فيُعاد الحجزُ لاحقًا فيُنشأ **موعدٌ
-- ثانٍ للمريض نفسه**. ومهلةُ المطالبة (دقيقتان) تمنع التزاحم ولا تُصلح هذا: هي
-- تنتهي فتفتح الباب لموعدٍ ثانٍ بدل أن تدلّ على الأوّل.
--
-- والعلاج مفتاحُ ربطٍ دائم على الموعد نفسه — لا ختمًا عابرًا على الصفّ:
--   • إعادةُ المحاولة **تجد** الموعد المكتوب فتربطه بدل أن تكتب غيره،
--   • والفهرسُ الفريد يجعل القاعدة هي الحَكَم: صفُّ انتظارٍ واحد ⇐ موعدٌ واحد،
--     ولو تسابق عليه اثنان في اللحظة نفسها.
--
-- إضافيّةٌ بالكامل: العمود يقبل NULL، وكلُّ موعدٍ قائم يبقى كما هو.
ALTER TABLE appointments
  ADD COLUMN IF NOT EXISTS waiting_list_id INTEGER REFERENCES waiting_list(id) ON DELETE SET NULL;

-- فريدٌ جزئيّ: المواعيد التي لا تأتي من انتظار (وهي الأكثر) لا يحكمها هذا القيد،
-- و«NULL» لا يتصادم مع «NULL» فلا يحتاج استثناءً.
CREATE UNIQUE INDEX IF NOT EXISTS appointments_waiting_list_unique_idx
  ON appointments (waiting_list_id) WHERE waiting_list_id IS NOT NULL;
